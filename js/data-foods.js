/* 供搜索/合并自定义食物 */
window.allFoods = function () {
  try {
    const custom = JSON.parse(localStorage.getItem("fitday_custom_foods") || "[]");
    return window.FOODS.concat(custom.map(f => Object.assign({}, f, { cat: "custom" })));
  } catch (e) { return window.FOODS.slice(); }
};
window.findFood = function (id) {
  return window.allFoods().find(f => f.id === id) || null;
};
/* 按克数计算营养 */
window.foodNutri = function (food, grams) {
  const k = grams / 100;
  return {
    kcal: Math.round(food.kcal * k),
    p: +(food.p * k).toFixed(1),
    f: +(food.f * k).toFixed(1),
    c: +(food.c * k).toFixed(1)
  };
};
