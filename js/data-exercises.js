/* ============ 工具函数 ============ */
window.findEx = function (id) { return window.EXERCISES.find(e => e.id === id) || null; };
/* MET 消耗公式：kcal = MET × 3.5 × 体重kg ÷ 200 × 分钟 */
window.exKcal = function (ex, weightKg, minutes) {
  return Math.round(ex.met * 3.5 * weightKg / 200 * minutes);
};
window.searchExercises = function (kw) {
  kw = (kw || "").trim().toLowerCase();
  if (!kw) return window.EXERCISES;
  return window.EXERCISES.filter(e =>
    [e.name, e.en, e.group, e.cat, (e.target||[]).join(" ")].join(" ").toLowerCase().includes(kw) ||
    (e.target || []).some(t => t.includes(kw))
  );
};
